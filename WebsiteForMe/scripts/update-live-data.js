#!/usr/bin/env node
/* ==========================================================================
   update-live-data.js
   Saves a snapshot of your YouTube / Roblox / Discord data to data/live.js.

   On Cloudflare Pages the site fetches fresh data from /api/live
   (functions/api/live.js), so this snapshot is only the instant first
   paint + fallback. Re-run it before deploying to keep that fallback fresh:

       node scripts/update-live-data.js

   Settings live in config.js → live. If a source fails, the previous
   snapshot for that source is kept.
   ========================================================================== */
'use strict';

const fs = require('fs');
const path = require('path');
const vm = require('vm');
const { pathToFileURL } = require('url');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'data', 'live.js');

function loadConfig() {
    const ctx = {};
    vm.runInNewContext(`${fs.readFileSync(path.join(ROOT, 'config.js'), 'utf8')}\n;this.__cfg = siteConfig;`, ctx);
    return ctx.__cfg;
}

function loadPrevious() {
    try {
        const ctx = { window: {} };
        vm.runInNewContext(fs.readFileSync(OUT, 'utf8'), ctx);
        return ctx.window.liveData || {};
    } catch (e) {
        return {};
    }
}

async function main() {
    const { fetchAll } = await import(pathToFileURL(path.join(ROOT, 'lib', 'live-sources.mjs')).href);
    const cfg = loadConfig();
    const live = cfg.live || {};
    const invite = live.discord && cfg.community && cfg.community.invite;
    const prev = loadPrevious();

    const data = await fetchAll({
        youtube: live.youtube,
        roblox: live.roblox,
        discordInvite: invite && invite !== '#' ? invite : ''
    });

    ['youtube', 'roblox', 'discord'].forEach((name) => {
        if (data[name]) console.log(`✓ ${name}`);
        else if (data.errors && data.errors[name]) {
            if (prev[name]) data[name] = prev[name];
            console.warn(`✗ ${name}: ${data.errors[name]}${prev[name] ? ' (kept previous data)' : ''}`);
        }
    });
    delete data.errors;

    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, `/* Auto-generated by scripts/update-live-data.js. Don't edit by hand. */\nwindow.liveData = ${JSON.stringify(data, null, 2)};\n`);
    console.log(`Wrote ${path.relative(ROOT, OUT)}`);
}

main().catch((e) => {
    console.error(e);
    process.exit(1);
});
